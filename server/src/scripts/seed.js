async function seed() {
  console.log('🌱 Starting database seeding (Indian Marketplaces, 100 Products, INR)...');
  await connectDB();

  console.log('🧹 Clearing old collections...');
  await PriceHistory.deleteMany({});
  await MarketplaceProduct.deleteMany({});
  await Product.deleteMany({});
  await Marketplace.deleteMany({});

  // 1. Create Marketplaces
  console.log('🏬 Inserting Indian e-commerce marketplaces...');
  const marketplaces = await Marketplace.insertMany(MARKETPLACES_DATA);

  // 2. Create Products
  console.log(`📦 Inserting ${PRODUCTS_DATA.length} products...`);
  const products = await Product.insertMany(PRODUCTS_DATA);

  // 3. Create Marketplace listings and 30-day Price Histories
  console.log('📈 Seeding prices and historical fluctuations...');
  const now = new Date();

  for (const product of products) {
    const origData = PRODUCTS_DATA.find((p) => p.name === product.name);
    if (!origData) continue;

    const basePrice = origData.basePrice;
    
    // Select 3 to 5 random stores to list this product
    const shuffledMarketplaces = [...marketplaces].sort(() => 0.5 - Math.random());
    const storeCount = 3 + Math.floor(Math.random() * 3); // 3, 4, or 5 stores
    const selectedStores = shuffledMarketplaces.slice(0, storeCount);

    for (const store of selectedStores) {
      // Fluctuate the base price slightly per store (e.g. within -8% to +5% of base price)
      const storeDeviation = 1 + (Math.random() * 0.13 - 0.08);
      const storeBasePrice = Math.round(basePrice * storeDeviation);

      // Generate 30 days of price points
      const dailyPriceHistory = [];
      let currentPrice = storeBasePrice;

      for (let i = 30; i >= 0; i--) {
        const timestamp = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
        
        // Fluctuate day-to-day (average ±1.5%)
        let dailyFactor = 1 + (Math.random() * 0.03 - 0.015);

        // Inject seasonal sale events
        if (i === 15) {
          dailyFactor = 0.88; // 12% drop
        } else if (i === 5) {
          dailyFactor = 0.82; // 18% drop
        }

        const price = Math.round(storeBasePrice * dailyFactor);
        dailyPriceHistory.push({ price, timestamp });

        if (i === 0) {
          currentPrice = price;
        }
      }

      const originalPrice = Math.round(storeBasePrice * (1.10 + Math.random() * 0.15)); // MRP is 10-25% higher
      const sku = `${store.code.substring(0, 3).toUpperCase()}-${product.brand.substring(0, 3).toUpperCase()}-${Math.floor(Math.random() * 900000 + 100000)}`;
      const urlPath = `product/${product.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;

      // Create MarketplaceProduct Offer listing
      const mpProduct = await MarketplaceProduct.create({
        product: product._id,
        marketplace: store._id,
        sku,
        url: `${store.baseUrl}/${urlPath}`,
        currentPrice,
        originalPrice,
        currency: 'INR',
        isAvailable: Math.random() > 0.08, // 92% available
        lastUpdated: now,
      });

      // Insert PriceHistory documents
      const historyDocs = dailyPriceHistory.map((h) => ({
        marketplaceProduct: mpProduct._id,
        price: h.price,
        timestamp: h.timestamp,
      }));

      await PriceHistory.insertMany(historyDocs);
    }
  }

  console.log('✅ Seeding of 100 Products across 6 Indian stores completed successfully!');
  await disconnectDB();
}

seed().catch(async (err) => {
  console.error('❌ Seeding failed:', err);
  await disconnectDB();
  process.exit(1);
});
